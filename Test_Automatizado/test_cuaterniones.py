@pytest.mark.parametrize("p", ODD_PRIMES)
def test_multiplicative_identity(p: int):
    """Propiedad 1: Identidad bilateral e * q = q * e = q para todo q en H(Z_p)."""
    e = quat_create(1, 0, 0, 0, p)
    for q in all_quaternions(p):
        assert quat_mul(e, q, p) == q, f"Falló e * q = q para q={q}, p={p}"
        assert quat_mul(q, e, p) == q, f"Falló q * e = q para q={q}, p={p}"


@pytest.mark.parametrize("p", [2] + EXTENDED_PRIMES)
def test_imaginary_units_squares(p: int):
    """Propiedad 2: Cuadrados de unidades imaginarias i^2 = j^2 = k^2 = -1 (mod p)."""
    minus_one = quat_create(-1, 0, 0, 0, p)
    i = quat_create(0, 1, 0, 0, p)
    j = quat_create(0, 0, 1, 0, p)
    k = quat_create(0, 0, 0, 1, p)

    assert quat_mul(i, i, p) == minus_one, f"Falló i^2 = -1 en p={p}"
    assert quat_mul(j, j, p) == minus_one, f"Falló j^2 = -1 en p={p}"
    assert quat_mul(k, k, p) == minus_one, f"Falló k^2 = -1 en p={p}"


@pytest.mark.parametrize("p", EXTENDED_PRIMES)
def test_non_commutativity(p: int):
    """Propiedad 3: No conmutatividad i * j = k, j * i = -k y relaciones cíclicas."""
    i = quat_create(0, 1, 0, 0, p)
    j = quat_create(0, 0, 1, 0, p)
    k = quat_create(0, 0, 0, 1, p)

    minus_i = quat_create(0, -1, 0, 0, p)
    minus_j = quat_create(0, 0, -1, 0, p)
    minus_k = quat_create(0, 0, 0, -1, p)

    assert quat_mul(i, j, p) == k, f"Falló i * j = k en p={p}"
    assert quat_mul(j, i, p) == minus_k, f"Falló j * i = -k en p={p}"
    assert quat_mul(i, j, p) != quat_mul(j, i, p), f"i y j conmutaron en p={p}"

    # Relaciones cíclicas completas de Hamilton
    assert quat_mul(j, k, p) == i
    assert quat_mul(k, j, p) == minus_i
    assert quat_mul(k, i, p) == j
    assert quat_mul(i, k, p) == minus_j


@pytest.mark.parametrize("p", EXTENDED_PRIMES)
def test_associativity(p: int):
    """
    Propiedad 4: Asociatividad de la multiplicación x * (q * h) = (x * q) * h.
    Exhaustiva sobre las 81^3 = 531,441 ternas en p=3 y muestreada para p > 3.
    """
    if p == 3:
        elems = all_quaternions(p)
        triples = itertools.product(elems, repeat=3)
    else:
        xs = sample_quaternions(p, 15, seed=101)
        qs = sample_quaternions(p, 15, seed=202)
        hs = sample_quaternions(p, 15, seed=303)
        triples = itertools.product(xs, qs, hs)

    for x, q, h in triples:
        lhs = quat_mul(x, quat_mul(q, h, p), p)
        rhs = quat_mul(quat_mul(x, q, p), h, p)
        assert lhs == rhs, f"Falló asociatividad en p={p} para {(x, q, h)}"


@pytest.mark.parametrize("p", EXTENDED_PRIMES)
def test_distributivity_left_and_right(p: int):
    """
    Propiedad 5: Distributividad bilateral:
      - Izquierda: x * (q + h) = x * q + x * h
      - Derecha:   (q + h) * x = q * x + h * x
    """
    if p == 3:
        elems = all_quaternions(p)
        triples = itertools.product(elems, repeat=3)
    else:
        xs = sample_quaternions(p, 15, seed=404)
        qs = sample_quaternions(p, 15, seed=505)
        hs = sample_quaternions(p, 15, seed=606)
        triples = itertools.product(xs, qs, hs)

    for x, q, h in triples:
        q_plus_h = quat_add(q, h, p)

        # Distributividad por la izquierda: x * (q + h) == x * q + x * h
        lhs_left = quat_mul(x, q_plus_h, p)
        rhs_left = quat_add(quat_mul(x, q, p), quat_mul(x, h, p), p)
        assert lhs_left == rhs_left, f"Falló distributividad izquierda en p={p} para {(x, q, h)}"

        # Distributividad por la derecha: (q + h) * x == q * x + h * x
        lhs_right = quat_mul(q_plus_h, x, p)
        rhs_right = quat_add(quat_mul(q, x, p), quat_mul(h, x, p), p)
        assert lhs_right == rhs_right, f"Falló distributividad derecha en p={p} para {(x, q, h)}"


@pytest.mark.parametrize("p", ODD_PRIMES)
def test_invertible_elements_and_count(p: int):
    """
    Propiedad 6: Invertibilidad bilateral q * u = e = u * q y conteo exacto
    |H(Z_p)^x| = p^4 - p^3 - p^2 + p para primos impares.
    """
    e = quat_create(1, 0, 0, 0, p)
    elements = all_quaternions(p)
    invertible_count = 0

    for q in elements:
        u = quat_inv(q, p)
        if u is not None:
            assert quat_mul(q, u, p) == e, f"Falló q * u = e para q={q}, u={u}, p={p}"
            assert quat_mul(u, q, p) == e, f"Falló u * q = e para q={q}, u={u}, p={p}"
            invertible_count += 1
        elif p == 3:
            # En p=3 verificamos exhaustivamente que ningún candidato invierte a q
            assert all(
                quat_mul(q, cand, p) != e and quat_mul(cand, q, p) != e
                for cand in elements
            ), f"Elemento {q} marcado como no invertible tiene inverso en p={p}"

    expected_count = p**4 - p**3 - p**2 + p
    assert invertible_count == expected_count, (
        f"Conteo de invertibles incorrecto para p={p}: "
        f"obtenido {invertible_count}, esperado {expected_count}"
    )


