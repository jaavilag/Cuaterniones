"""
Automated test suite for quaternion algebra H(Z_p) over prime fields Z_p.
Validates:
  1. Multiplicative identity: e * q = q * e = q
  2. Imaginary unit squares: i^2 = j^2 = k^2 = -1 (mod p)
  3. Non-commutativity: i * j = k and j * i = -k (plus cyclic relations)
  4. Associativity of multiplication: x * (q * h) = (x * q) * h
  5. Left and right distributivity: x * (q + h) = x * q + x * h and (q + h) * x = q * x + h * x
  6. Invertibility and unit group count: q * u = e = u * q and |H(Z_p)^x| = p^4 - p^3 - p^2 + p
"""

import itertools
import random
import pytest

Quaternion = tuple[int, int, int, int]

ODD_PRIMES = [3, 5, 7]
EXTENDED_PRIMES = [3, 5, 7, 11]


# ==============================================================================
# 1. DEFINICIÓN DE OPERACIONES EN H(Z_p)
# ==============================================================================

def quat_create(a: int, b: int, c: int, d: int, p: int) -> Quaternion:
    """Construye el cuaternión a + bi + cj + dk reducido módulo p."""
    return (a % p, b % p, c % p, d % p)


def quat_add(q1: Quaternion, q2: Quaternion, p: int) -> Quaternion:
    """Suma de dos cuaterniones en H(Z_p)."""
    return (
        (q1[0] + q2[0]) % p,
        (q1[1] + q2[1]) % p,
        (q1[2] + q2[2]) % p,
        (q1[3] + q2[3]) % p,
    )


def quat_mul(q1: Quaternion, q2: Quaternion, p: int) -> Quaternion:
    """Producto de Hamilton de dos cuaterniones en H(Z_p)."""
    a1, b1, c1, d1 = q1
    a2, b2, c2, d2 = q2
    return (
        (a1 * a2 - b1 * b2 - c1 * c2 - d1 * d2) % p,
        (a1 * b2 + b1 * a2 + c1 * d2 - d1 * c2) % p,
        (a1 * c2 - b1 * d2 + c1 * a2 + d1 * b2) % p,
        (a1 * d2 + b1 * c2 - c1 * b2 + d1 * a2) % p,
    )


def quat_norm(q: Quaternion, p: int) -> int:
    """Norma reducida N(q) = a^2 + b^2 + c^2 + d^2 (mod p)."""
    a, b, c, d = q
    return (a * a + b * b + c * c + d * d) % p


def quat_inv(q: Quaternion, p: int) -> Quaternion | None:
    """
    Calcula el inverso multiplicativo q^(-1) = conj(q) * N(q)^(-1) mod p.
    Devuelve None si N(q) == 0 (mod p), es decir, si q es divisor de cero.
    """
    norm = quat_norm(q, p)
    if norm == 0:
        return None
    norm_inv = pow(norm, -1, p)
    a, b, c, d = q
    return (
        (a * norm_inv) % p,
        (-b * norm_inv) % p,
        (-c * norm_inv) % p,
        (-d * norm_inv) % p,
    )


# ==============================================================================
# 2. GENERADORES AUXILIARES PARA PRUEBAS EXHAUSTIVAS Y MUESTREO DETERMINISTA
# ==============================================================================

def all_quaternions(p: int) -> list[Quaternion]:
    """Genera los p^4 elementos de H(Z_p)."""
    return [quat_create(a, b, c, d, p) for a, b, c, d in itertools.product(range(p), repeat=4)]


def sample_quaternions(p: int, count: int, seed: int) -> list[Quaternion]:
    """Genera una muestra determinista de cuaterniones en H(Z_p)."""
    rng = random.Random(seed)
    return [
        quat_create(rng.randrange(p), rng.randrange(p), rng.randrange(p), rng.randrange(p), p)
        for _ in range(count)
    ]


